//
//  PasteInserter.swift
//  voxim
//
//  Inserts text by placing it on the clipboard and posting ⌘V, then restoring the user's
//  previous clipboard. Works in native, browser, Electron and terminal text inputs alike.
//

import AppKit
import Carbon.HIToolbox

/// Seam for the system-level side effects so clipboard handling can be unit tested.
protocol KeystrokePosting {
    func postPaste()
    var isSecureInputEnabled: Bool { get }
}

struct SystemKeystrokePoster: KeystrokePosting {
    func postPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        // Explicit flags so any modifiers the user is holding don't alter the paste.
        for keyDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: keyDown)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    var isSecureInputEnabled: Bool { IsSecureEventInputEnabled() }
}

final class PasteInserter: DictationSink {
    /// nspasteboard.org markers: clipboard managers skip these entries.
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private let pasteboard: NSPasteboard
    private let poster: any KeystrokePosting
    private let checkFocus: Bool
    /// How long the target app gets to read the clipboard before it is restored.
    private let restoreDelay: Duration

    init(
        pasteboard: NSPasteboard = .general,
        poster: any KeystrokePosting = SystemKeystrokePoster(),
        checkFocus: Bool = true,
        restoreDelay: Duration = .milliseconds(250)
    ) {
        self.pasteboard = pasteboard
        self.poster = poster
        self.checkFocus = checkFocus
        self.restoreDelay = restoreDelay
    }

    func insert(_ text: String, expecting app: FocusedApp?) async throws {
        if checkFocus {
            guard AXAccess.isTrusted else { throw InsertionError.accessibilityDenied }
            if let app, let now = FocusedApp.current, now.pid != app.pid {
                throw InsertionError.focusChanged(from: app.name, to: now.name)
            }
            guard AXAccess.hasFocusedElement else { throw InsertionError.noFocusedField }
        }
        guard !poster.isSecureInputEnabled else { throw InsertionError.secureInput }

        let saved = snapshot()
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        poster.postPaste()
        try? await Task.sleep(for: restoreDelay)

        // If something else wrote to the clipboard meanwhile, leave it alone.
        guard pasteboard.changeCount == ourChange else { return }
        restore(saved)
    }

    private func snapshot() -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    private func restore(_ items: [NSPasteboardItem]) {
        pasteboard.clearContents()
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }
}
